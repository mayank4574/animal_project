async function seed() {
  await mongoose.connect(process.env.MONGO_URI);
  await Provider.deleteMany({});
  const created = await Provider.insertMany(
    providers.map((p) => ({
      ...p,
      slug: p.name
        .toLowerCase()
        .replace(/[^a-z0-9\s-]/g, '')
        .replace(/\s+/g, '-')
        .replace(/-+/g, '-'),
    }))
  );
  console.log(`Seeded ${created.length} demo providers successfully!`);
  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error('Seed failed:', err.message);
  process.exit(1);
});
